//go:build ignore

// Generates tables.go from the range lists in testdata/, which were dumped from
// Rust's standard library (the dump program is in the git tag rust-reference,
// as internal/ucd/testdata/dump.rs). Run with `go generate ./internal/ucd`.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"
	"strings"
)

func read(name string) [][2]uint32 {
	f, err := os.Open("testdata/" + name)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	var out [][2]uint32
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fields := strings.Fields(sc.Text())
		if len(fields) != 2 {
			log.Fatalf("%s: bad line %q", name, sc.Text())
		}
		a, err1 := strconv.ParseUint(fields[0], 16, 32)
		b, err2 := strconv.ParseUint(fields[1], 16, 32)
		if err1 != nil || err2 != nil {
			log.Fatalf("%s: bad line %q", name, sc.Text())
		}
		out = append(out, [2]uint32{uint32(a), uint32(b)})
	}
	return out
}

func emit(buf *bytes.Buffer, name, doc, element string, rows [][2]uint32) {
	fmt.Fprintf(buf, "// %s\nvar %s = [][2]%s{\n", doc, name, element)
	for i, row := range rows {
		if i%6 == 0 {
			buf.WriteString("\t")
		}
		fmt.Fprintf(buf, "{0x%X, 0x%X},", row[0], row[1])
		if i%6 == 5 || i == len(rows)-1 {
			buf.WriteString("\n")
		} else {
			buf.WriteString(" ")
		}
	}
	buf.WriteString("}\n\n")
}

func main() {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen.go from testdata/*.txt (Rust 1.96.1 standard library, Unicode 17.0.0); DO NOT EDIT.\n\npackage ucd\n\n")
	for _, t := range []struct{ name, doc, file string }{
		{"alphabeticRanges", "alphabeticRanges lists the scalars for which char::is_alphabetic is true.", "rust-alphabetic.txt"},
		{"numericRanges", "numericRanges lists the scalars for which char::is_numeric is true.", "rust-numeric.txt"},
		{"whitespaceRanges", "whitespaceRanges lists the scalars for which char::is_whitespace is true.", "rust-whitespace.txt"},
		{"controlRanges", "controlRanges lists the scalars for which char::is_control is true.", "rust-control.txt"},
		{"uppercaseRanges", "uppercaseRanges lists the scalars for which char::is_uppercase is true.", "rust-uppercase.txt"},
		{"lowercaseRanges", "lowercaseRanges lists the scalars for which char::is_lowercase is true.", "rust-lowercase.txt"},
	} {
		emit(&buf, t.name, t.doc, "rune", read(t.file))
	}
	emit(&buf, "lowerMap", "lowerMap pairs each scalar with its single-scalar lower-case, sorted by scalar.", "rune", read("rust-lower-map.txt"))
	out, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
