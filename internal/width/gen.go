//go:build ignore

// gen writes tables.go from the table dumps in testdata/. Run it with
// "go generate" (see width.go) from this directory.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"
	"strings"
)

// readLines returns the whitespace-separated fields of every non-comment line.
func readLines(name string) [][]string {
	data, err := os.ReadFile("testdata/" + name)
	if err != nil {
		log.Fatal(err)
	}
	var lines [][]string
	for _, line := range strings.Split(string(data), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		lines = append(lines, strings.Fields(line))
	}
	return lines
}

func hexField(name string, f string) int {
	v, err := strconv.ParseInt(f, 16, 32)
	if err != nil {
		log.Fatalf("%s: %v", name, err)
	}
	return int(v)
}

func decField(name string, f string) int {
	v, err := strconv.Atoi(f)
	if err != nil {
		log.Fatalf("%s: %v", name, err)
	}
	return v
}

// emit writes entries as a Go composite literal, perLine entries per line.
func emit(buf *bytes.Buffer, entries []string, perLine int) {
	for i, e := range entries {
		if i%perLine == 0 {
			buf.WriteString("\n\t")
		} else {
			buf.WriteString(" ")
		}
		buf.WriteString(e)
		buf.WriteString(",")
	}
	buf.WriteString("\n")
}

// runeRanges turns a "START END" dump into runeRange literals.
func runeRanges(buf *bytes.Buffer, varName, doc, file string) {
	var entries []string
	prevHi := -1
	for _, f := range readLines(file) {
		lo, hi := hexField(file, f[0]), hexField(file, f[1])
		if lo > hi || lo <= prevHi {
			log.Fatalf("%s: ranges out of order at %s", file, f[0])
		}
		prevHi = hi
		entries = append(entries, fmt.Sprintf("{0x%04X, 0x%04X}", lo, hi))
	}
	fmt.Fprintf(buf, "// %s %s\n// Source: testdata/%s.\nvar %s = [...]runeRange{", varName, doc, file, varName)
	emit(buf, entries, 4)
	buf.WriteString("}\n\n")
}

func main() {
	var buf bytes.Buffer
	buf.WriteString(`// Code generated by "go run gen.go" from testdata/*.txt; DO NOT EDIT.
// The tables are those of unicode-width 0.2.2 (Unicode 17.0.0).

package width

`)

	// lookup.txt: START END RAW WIDTH INFO. Only the raw 2-bit trie entry is stored; the width
	// and WidthInfo of the special entries (raw == 3) come from lookupWidth.
	var runs []string
	prevRaw, next := -1, 0
	for _, f := range readLines("lookup.txt") {
		lo, hi := hexField("lookup.txt", f[0]), hexField("lookup.txt", f[1])
		raw, width := decField("lookup.txt", f[2]), decField("lookup.txt", f[3])
		info, err := strconv.ParseUint(f[4], 16, 16)
		if err != nil {
			log.Fatal(err)
		}
		if lo != next {
			log.Fatalf("lookup.txt: gap before %X", lo)
		}
		next = hi + 1
		if raw < 3 && (width != raw || info != 0) {
			log.Fatalf("lookup.txt: %X..%X raw %d but width %d info %X", lo, hi, raw, width, info)
		}
		if raw != prevRaw {
			runs = append(runs, fmt.Sprintf("{0x%04X, %d}", lo, raw))
			prevRaw = raw
		}
	}
	if next != 0x110000 {
		log.Fatalf("lookup.txt: ends at %X", next)
	}
	buf.WriteString(`// widthRuns holds, for every maximal run of code points with the same raw trie entry,
// the first code point of the run and the entry (0, 1, 2, or 3 = "special, see lookupWidth").
// A run extends up to the start of the next one; the last run ends at U+10FFFF.
// Source: testdata/lookup.txt.
var widthRuns = [...]widthRun{`)
	emit(&buf, runs, 6)
	buf.WriteString("}\n\n")

	runeRanges(&buf, "nonTransparentZeroWidths",
		"lists the zero-width code points that are not Joining_Type=Transparent.", "non_transparent_zero_widths.txt")
	runeRanges(&buf, "emojiPresentationSeq",
		"lists the code points that start an emoji presentation sequence.", "emoji_presentation_seq.txt")
	runeRanges(&buf, "textPresentationSeq",
		"lists the non-ideographic code points that form a text presentation sequence.", "text_presentation_seq.txt")
	runeRanges(&buf, "emojiModifierBase",
		"lists the Emoji_Modifier_Base code points.", "emoji_modifier_base.txt")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
