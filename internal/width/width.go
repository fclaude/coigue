// Package width computes terminal display widths exactly like the Rust crate unicode-width
// 0.2.2 (Unicode 17.0.0, ambiguous-width characters narrow, i.e. width() and not width_cjk()).
//
// Go libraries such as go-runewidth, rivo/uniseg and charmbracelet/x/ansi disagree with that crate
// for thousands of code points (U+0605, U+0890, U+08E2, U+09BE, U+0600, ...), so the data here
// is generated from the crate itself.
//
// Char is UnicodeWidthChar::width. String is UnicodeWidthStr::width: it is not the sum of the
// character widths, because emoji sequences, regional indicator pairs, Arabic Lam-Alef,
// Khmer coeng and several other ligatures, and CRLF change the total. widthInStr is the
// reverse-fold state machine of the crate's tables.rs, ported arm by arm.
//
// # Regenerating the tables
//
// tables.go is generated by gen.go from the dumps in testdata/ (go generate runs it):
//
//	go generate ./internal/width
//
// The dumps themselves come from the Rust crate: testdata/dump/main.rs was a small Rust program
// built next to a copy of unicode-width-0.2.2/src/tables.rs with testdata/dump/tables_patch.rs
// appended (the patch only exposed private functions). Both are in the git tag rust-reference,
// with the commands in the header of main.rs. To move to another unicode-width release, produce
// new dumps with that program, regenerate, and compare widthInStr and lookupWidth with the new
// tables.rs by hand, because those two functions are hand-ported code and not generated.
package width

import (
	"slices"
	"sort"
	"unicode/utf8"
)

//go:generate go run gen.go

// Char returns the display width of r and true, or 0 and false for the C0 and C1 control
// characters (Rust's None). Values that are not Unicode scalar values (surrogates, out of range)
// are treated like U+FFFD, as Go itself does when converting them to a string.
func Char(r rune) (w int, ok bool) {
	if !validScalar(r) {
		r = utf8.RuneError
	}
	if r < 0x7F {
		if r >= 0x20 {
			// U+0020 to U+007F (exclusive) are single-width ASCII code points.
			return 1, true
		}
		// U+0000 to U+0020 (exclusive) are control codes.
		return 0, false
	}
	if r >= 0xA0 {
		// No characters >= U+00A0 are control codes, so the lookup tables apply.
		w, _ := lookupWidth(r)
		return w, true
	}
	// U+007F to U+00A0 (exclusive) are control codes.
	return 0, false
}

// String returns the display width of s in columns. Bytes that are not valid UTF-8 count as
// U+FFFD, one per byte (what ranging over the string yields).
func String(s string) int {
	sum := 0
	info := infoDefault
	for i := len(s); i > 0; {
		c, size := utf8.DecodeLastRuneInString(s[:i])
		i -= size
		var add int
		add, info = widthInStr(c, info)
		sum += add
	}
	return sum
}

func validScalar(r rune) bool {
	return r >= 0 && r <= utf8.MaxRune && !(0xD800 <= r && r <= 0xDFFF)
}

type runeRange struct{ lo, hi rune }

type widthRun struct {
	start rune
	raw   uint8
}

func inRanges(table []runeRange, c rune) bool {
	_, found := slices.BinarySearchFunc(table, c, func(r runeRange, c rune) int {
		if c < r.lo {
			return 1
		}
		if c > r.hi {
			return -1
		}
		return 0
	})
	return found
}

// widthInfo is the Rust crate's WidthInfo: the state carried through the reverse fold, with
// flag bits in the top byte (VS16, VS15) and ligature-transparent states in the middle.
type widthInfo uint16

const ligatureTransparentMask = 0b0010_0000_0000_0000

const (
	// No special handling necessary.
	infoDefault                              widthInfo = 0
	infoLineFeed                             widthInfo = 0b0000000000000001
	infoEmojiModifier                        widthInfo = 0b0000000000000010
	infoRegionalIndicator                    widthInfo = 0b0000000000000011
	infoSeveralRegionalIndicator             widthInfo = 0b0000000000000100
	infoEmojiPresentation                    widthInfo = 0b0000000000000101
	infoZWJEmojiPresentation                 widthInfo = 0b0001000000000110
	infoVS16ZWJEmojiPresentation             widthInfo = 0b1001000000000110
	infoKeycapZWJEmojiPresentation           widthInfo = 0b0001000000000111
	infoVS16KeycapZWJEmojiPresentation       widthInfo = 0b1001000000000111
	infoRegionalIndicatorZWJPresentation     widthInfo = 0b0000000000001001
	infoEvenRegionalIndicatorZWJPresentation widthInfo = 0b0000000000001010
	infoOddRegionalIndicatorZWJPresentation  widthInfo = 0b0000000000001011
	infoTagEndZWJEmojiPresentation           widthInfo = 0b0000000000010000
	infoTagD1EndZWJEmojiPresentation         widthInfo = 0b0000000000010001
	infoTagD2EndZWJEmojiPresentation         widthInfo = 0b0000000000010010
	infoTagD3EndZWJEmojiPresentation         widthInfo = 0b0000000000010011
	infoTagA1EndZWJEmojiPresentation         widthInfo = 0b0000000000011001
	infoTagA2EndZWJEmojiPresentation         widthInfo = 0b0000000000011010
	infoTagA3EndZWJEmojiPresentation         widthInfo = 0b0000000000011011
	infoTagA4EndZWJEmojiPresentation         widthInfo = 0b0000000000011100
	infoTagA5EndZWJEmojiPresentation         widthInfo = 0b0000000000011101
	infoTagA6EndZWJEmojiPresentation         widthInfo = 0b0000000000011110
	infoKiratRaiVowelSignE                   widthInfo = 0b0000000000100000
	infoKiratRaiVowelSignAI                  widthInfo = 0b0000000000100001
	infoVariationSelector123                 widthInfo = 0b0000001000000000
	infoVariationSelector15                  widthInfo = 0b0100000000000000
	infoVariationSelector16                  widthInfo = 0b1000000000000000
	infoJoiningGroupAlef                     widthInfo = 0b0011000011111111
	infoHebrewLetterLamed                    widthInfo = 0b0011100000000000
	infoZWJHebrewLetterLamed                 widthInfo = 0b0011110000000000
	infoBugineseLetterYa                     widthInfo = 0b0011100000000001
	infoZWJBugineseLetterYa                  widthInfo = 0b0011110000000001
	infoBugineseVowelSignIZWJLetterYa        widthInfo = 0b0011110000000010
	infoTifinaghConsonant                    widthInfo = 0b0011100000000011
	infoZWJTifinaghConsonant                 widthInfo = 0b0011110000000011
	infoTifinaghJoinerConsonant              widthInfo = 0b0011110000000100
	infoLisuToneLetterMyaNaJeu               widthInfo = 0b0011110000000101
	infoOldTurkicLetterOrkhonI               widthInfo = 0b0011100000000110
	infoZWJOldTurkicLetterOrkhonI            widthInfo = 0b0011110000000110
	infoKhmerCoengEligibleLetter             widthInfo = 0b0011110000000111
)

// isLigatureTransparent: whether this width mode is ligature_transparent (has the 5th MSB set).
func (i widthInfo) isLigatureTransparent() bool {
	return i&0b0000_1000_0000_0000 == 0b0000_1000_0000_0000
}

// setZWJBit sets the 6th MSB.
func (i widthInfo) setZWJBit() widthInfo {
	return i | 0b0000_0100_0000_0000
}

// isEmojiPresentation: the top bit is set.
func (i widthInfo) isEmojiPresentation() bool {
	return i&infoVariationSelector16 == infoVariationSelector16
}

func (i widthInfo) isZWJEmojiPresentation() bool {
	return i&0b1011_0000_0000_0000 == 0b1001_0000_0000_0000
}

// setEmojiPresentation sets the top bit.
//
// Rust oddity preserved: in the crate, `self.0 | VS16 & !VS15 & !VS1_2_3` parses as
// `self.0 | (VS16 & !VS15 & !VS1_2_3)`, which is `self.0 | VS16`: the VS15 and VS1-3 bits
// of self are not cleared although the expression reads as if they were.
func (i widthInfo) setEmojiPresentation() widthInfo {
	if i&ligatureTransparentMask == ligatureTransparentMask ||
		i&0b1001_0000_0000_0000 == 0b0001_0000_0000_0000 {
		return i | (infoVariationSelector16 &^ infoVariationSelector15 &^ infoVariationSelector123)
	}
	return infoVariationSelector16
}

// unsetEmojiPresentation clears the top bit.
func (i widthInfo) unsetEmojiPresentation() widthInfo {
	if i&ligatureTransparentMask == ligatureTransparentMask {
		return i &^ infoVariationSelector16
	}
	return infoDefault
}

// isTextPresentation: the 2nd bit is set.
func (i widthInfo) isTextPresentation() bool {
	return i&infoVariationSelector15 == infoVariationSelector15
}

// setTextPresentation sets the 2nd bit. Same precedence oddity as setEmojiPresentation.
func (i widthInfo) setTextPresentation() widthInfo {
	if i&ligatureTransparentMask == ligatureTransparentMask {
		return i | (infoVariationSelector15 &^ infoVariationSelector16 &^ infoVariationSelector123)
	}
	return infoVariationSelector15
}

// unsetTextPresentation clears the 2nd bit.
func (i widthInfo) unsetTextPresentation() widthInfo {
	return i &^ infoVariationSelector15
}

// isVS123: the 7th bit is set.
func (i widthInfo) isVS123() bool {
	return i&infoVariationSelector123 == infoVariationSelector123
}

// setVS123 sets the 7th bit. Same precedence oddity as setEmojiPresentation.
func (i widthInfo) setVS123() widthInfo {
	if i&ligatureTransparentMask == ligatureTransparentMask {
		return i | (infoVariationSelector123 &^ infoVariationSelector15 &^ infoVariationSelector16)
	}
	return infoVariationSelector123
}

// unsetVS123 clears the 7th bit.
func (i widthInfo) unsetVS123() widthInfo {
	return i &^ infoVariationSelector123
}

// rawWidth returns the 2-bit entry of the width trie for c (3 means special).
func rawWidth(c rune) uint8 {
	i := sort.Search(len(widthRuns), func(i int) bool { return widthRuns[i].start > c })
	return widthRuns[i-1].raw
}

// lookupWidth returns the UAX #11 based width of c and the width state it starts.
func lookupWidth(c rune) (int, widthInfo) {
	width := rawWidth(c)
	if width < 3 {
		return int(width), infoDefault
	}
	switch {
	case c == 0xA:
		return 1, infoLineFeed
	case c == 0x5DC:
		return 1, infoHebrewLetterLamed
	case 0x622 <= c && c <= 0x882:
		return 1, infoJoiningGroupAlef
	case 0x1780 <= c && c <= 0x17AF:
		return 1, infoKhmerCoengEligibleLetter
	case c == 0x17D8:
		return 3, infoDefault
	case c == 0x1A10:
		return 1, infoBugineseLetterYa
	case 0x2D31 <= c && c <= 0x2D6F:
		return 1, infoTifinaghConsonant
	case 0xA4FC <= c && c <= 0xA4FD:
		return 1, infoLisuToneLetterMyaNaJeu
	case c == 0xFE01:
		return 0, infoVariationSelector123
	case c == 0xFE0E:
		return 0, infoVariationSelector15
	case c == 0xFE0F:
		return 0, infoVariationSelector16
	case c == 0x10C03:
		return 1, infoOldTurkicLetterOrkhonI
	case c == 0x16D67:
		return 1, infoKiratRaiVowelSignE
	case c == 0x16D68:
		return 1, infoKiratRaiVowelSignAI
	case 0x1F1E6 <= c && c <= 0x1F1FF:
		return 1, infoRegionalIndicator
	case 0x1F3FB <= c && c <= 0x1F3FF:
		return 2, infoEmojiModifier
	}
	return 2, infoEmojiPresentation
}

// widthInStr returns the width that c adds to a string whose already-processed tail (the
// characters after c) left the state nextInfo, and the state for the character before c. The
// add is negative where a ligature takes width away from the character on its right.
func widthInStr(c rune, nextInfo widthInfo) (int, widthInfo) {
	if nextInfo.isEmojiPresentation() {
		if startsEmojiPresentationSeq(c) {
			width := 2
			if nextInfo.isZWJEmojiPresentation() {
				width = 0
			}
			return width, infoEmojiPresentation
		}
		nextInfo = nextInfo.unsetEmojiPresentation()
	}
	if c <= 0xA0 {
		switch {
		case c == '\n':
			return 1, infoLineFeed
		case c == '\r' && nextInfo == infoLineFeed:
			return 0, infoDefault
		}
		return 1, infoDefault
	}
	// Fast path
	if nextInfo != infoDefault {
		if c == 0xFE0F {
			return 0, nextInfo.setEmojiPresentation()
		}
		if c == 0xFE01 {
			return 0, nextInfo.setVS123()
		}
		if c == 0xFE0E {
			return 0, nextInfo.setTextPresentation()
		}
		if nextInfo.isTextPresentation() {
			if startsNonIdeographicTextPresentationSeq(c) {
				return 1, infoDefault
			}
			nextInfo = nextInfo.unsetTextPresentation()
		} else if nextInfo.isVS123() {
			if c == 0x2018 || c == 0x2019 || c == 0x201C || c == 0x201D {
				return 2, infoDefault
			}
			nextInfo = nextInfo.unsetVS123()
		}
		if nextInfo.isLigatureTransparent() {
			if c == 0x200D {
				return 0, nextInfo.setZWJBit()
			} else if isLigatureTransparent(c) {
				return 0, nextInfo
			}
		}

		switch {
		// Arabic Lam-Alef ligature
		case nextInfo == infoJoiningGroupAlef &&
			(c == 0x644 || 0x6B5 <= c && c <= 0x6B8 || c == 0x76A || c == 0x8A6 || c == 0x8C7):
			return 0, infoDefault
		case nextInfo == infoJoiningGroupAlef && isTransparentZeroWidth(c):
			return 0, infoJoiningGroupAlef

		// Hebrew Alef-ZWJ-Lamed ligature
		case nextInfo == infoZWJHebrewLetterLamed && c == 0x05D0:
			return 0, infoDefault

		// Khmer coeng signs
		case nextInfo == infoKhmerCoengEligibleLetter && c == 0x17D2:
			return -1, infoDefault

		// Buginese <a, -i> ZWJ ya ligature
		case nextInfo == infoZWJBugineseLetterYa && c == 0x1A17:
			return 0, infoBugineseVowelSignIZWJLetterYa
		case nextInfo == infoBugineseVowelSignIZWJLetterYa && c == 0x1A15:
			return 0, infoDefault

		// Tifinagh bi-consonants
		case (nextInfo == infoTifinaghConsonant || nextInfo == infoZWJTifinaghConsonant) && c == 0x2D7F:
			return 1, infoTifinaghJoinerConsonant
		case nextInfo == infoZWJTifinaghConsonant && (0x2D31 <= c && c <= 0x2D65 || c == 0x2D6F):
			return 0, infoDefault
		case nextInfo == infoTifinaghJoinerConsonant && (0x2D31 <= c && c <= 0x2D65 || c == 0x2D6F):
			return -1, infoDefault

		// Lisu tone letter combinations
		case nextInfo == infoLisuToneLetterMyaNaJeu && 0xA4F8 <= c && c <= 0xA4FB:
			return 0, infoDefault

		// Old Turkic ligature
		case nextInfo == infoZWJOldTurkicLetterOrkhonI && c == 0x10C32:
			return 0, infoDefault

		// Emoji modifier
		case nextInfo == infoEmojiModifier && isEmojiModifierBase(c):
			return 0, infoEmojiPresentation

		// Regional indicator
		case (nextInfo == infoRegionalIndicator || nextInfo == infoSeveralRegionalIndicator) &&
			0x1F1E6 <= c && c <= 0x1F1FF:
			return 1, infoSeveralRegionalIndicator

		// ZWJ emoji
		case (nextInfo == infoEmojiPresentation ||
			nextInfo == infoSeveralRegionalIndicator ||
			nextInfo == infoEvenRegionalIndicatorZWJPresentation ||
			nextInfo == infoOddRegionalIndicatorZWJPresentation ||
			nextInfo == infoEmojiModifier) && c == 0x200D:
			return 0, infoZWJEmojiPresentation
		case nextInfo == infoZWJEmojiPresentation && c == 0x20E3:
			return 0, infoKeycapZWJEmojiPresentation
		// Rust oddity preserved: the next two arms are unreachable. A state with the VS16 bit
		// set is consumed (returned or cleared) by the check at the top of widthInStr, and
		// unsetEmojiPresentation turns these two states into infoDefault.
		case nextInfo == infoVS16ZWJEmojiPresentation && startsEmojiPresentationSeq(c):
			return 0, infoEmojiPresentation
		case nextInfo == infoVS16KeycapZWJEmojiPresentation && ('0' <= c && c <= '9' || c == '#' || c == '*'):
			return 0, infoEmojiPresentation
		case nextInfo == infoZWJEmojiPresentation && 0x1F1E6 <= c && c <= 0x1F1FF:
			return 1, infoRegionalIndicatorZWJPresentation
		case (nextInfo == infoRegionalIndicatorZWJPresentation || nextInfo == infoOddRegionalIndicatorZWJPresentation) &&
			0x1F1E6 <= c && c <= 0x1F1FF:
			return -1, infoEvenRegionalIndicatorZWJPresentation
		case nextInfo == infoEvenRegionalIndicatorZWJPresentation && 0x1F1E6 <= c && c <= 0x1F1FF:
			return 3, infoOddRegionalIndicatorZWJPresentation
		case nextInfo == infoZWJEmojiPresentation && 0x1F3FB <= c && c <= 0x1F3FF:
			return 0, infoEmojiModifier
		case nextInfo == infoZWJEmojiPresentation && c == 0xE007F:
			return 0, infoTagEndZWJEmojiPresentation
		case nextInfo == infoTagEndZWJEmojiPresentation && 0xE0061 <= c && c <= 0xE007A:
			return 0, infoTagA1EndZWJEmojiPresentation
		case nextInfo == infoTagA1EndZWJEmojiPresentation && 0xE0061 <= c && c <= 0xE007A:
			return 0, infoTagA2EndZWJEmojiPresentation
		case nextInfo == infoTagA2EndZWJEmojiPresentation && 0xE0061 <= c && c <= 0xE007A:
			return 0, infoTagA3EndZWJEmojiPresentation
		case nextInfo == infoTagA3EndZWJEmojiPresentation && 0xE0061 <= c && c <= 0xE007A:
			return 0, infoTagA4EndZWJEmojiPresentation
		case nextInfo == infoTagA4EndZWJEmojiPresentation && 0xE0061 <= c && c <= 0xE007A:
			return 0, infoTagA5EndZWJEmojiPresentation
		case nextInfo == infoTagA5EndZWJEmojiPresentation && 0xE0061 <= c && c <= 0xE007A:
			return 0, infoTagA6EndZWJEmojiPresentation
		case (nextInfo == infoTagEndZWJEmojiPresentation ||
			nextInfo == infoTagA1EndZWJEmojiPresentation ||
			nextInfo == infoTagA2EndZWJEmojiPresentation ||
			nextInfo == infoTagA3EndZWJEmojiPresentation ||
			nextInfo == infoTagA4EndZWJEmojiPresentation) && 0xE0030 <= c && c <= 0xE0039:
			return 0, infoTagD1EndZWJEmojiPresentation
		case nextInfo == infoTagD1EndZWJEmojiPresentation && 0xE0030 <= c && c <= 0xE0039:
			return 0, infoTagD2EndZWJEmojiPresentation
		case nextInfo == infoTagD2EndZWJEmojiPresentation && 0xE0030 <= c && c <= 0xE0039:
			return 0, infoTagD3EndZWJEmojiPresentation
		case (nextInfo == infoTagA3EndZWJEmojiPresentation ||
			nextInfo == infoTagA4EndZWJEmojiPresentation ||
			nextInfo == infoTagA5EndZWJEmojiPresentation ||
			nextInfo == infoTagA6EndZWJEmojiPresentation ||
			nextInfo == infoTagD3EndZWJEmojiPresentation) && c == 0x1F3F4:
			return 0, infoEmojiPresentation
		case nextInfo == infoZWJEmojiPresentation && lookupInfo(c) == infoEmojiPresentation:
			return 0, infoEmojiPresentation

		case nextInfo == infoKiratRaiVowelSignE && c == 0x16D63:
			return 0, infoDefault
		case nextInfo == infoKiratRaiVowelSignE && c == 0x16D67:
			return 0, infoKiratRaiVowelSignAI
		case nextInfo == infoKiratRaiVowelSignE && c == 0x16D68:
			return 1, infoKiratRaiVowelSignE
		case nextInfo == infoKiratRaiVowelSignE && c == 0x16D69:
			return 0, infoDefault
		case nextInfo == infoKiratRaiVowelSignAI && c == 0x16D63:
			return 0, infoDefault

		// Fallback
		default:
		}
	}

	w, info := lookupWidth(c)
	return w, info
}

func lookupInfo(c rune) widthInfo {
	_, info := lookupWidth(c)
	return info
}

// isTransparentZeroWidth: whether c is a zero-width character with Joining_Type=Transparent.
// Used by the Alef-Lamed ligatures. See also isLigatureTransparent, a near-subset of this
// (only ZWJ is excepted) which is transparent for non-Arabic ligatures.
func isTransparentZeroWidth(c rune) bool {
	if w, _ := lookupWidth(c); w != 0 {
		// Not zero-width
		return false
	}
	return !inRanges(nonTransparentZeroWidths[:], c)
}

// isLigatureTransparent: whether c is a default-ignorable combining mark or ZWJ. These
// characters won't interrupt non-Arabic ligatures.
func isLigatureTransparent(c rune) bool {
	switch {
	case c == 0x34F,
		0x17B4 <= c && c <= 0x17B5,
		0x180B <= c && c <= 0x180D,
		c == 0x180F,
		c == 0x200D,
		0xFE00 <= c && c <= 0xFE0F,
		0xE0100 <= c && c <= 0xE01EF:
		return true
	}
	return false
}

// startsEmojiPresentationSeq: whether c forms an emoji presentation sequence when followed by
// U+FE0F. Emoji presentation sequences are considered to have width 2.
func startsEmojiPresentationSeq(c rune) bool {
	return inRanges(emojiPresentationSeq[:], c)
}

// startsNonIdeographicTextPresentationSeq: whether c has default emoji presentation, but forms a
// text presentation sequence when followed by U+FE0E, and is not ideographic. Such sequences are
// considered to have width 1.
func startsNonIdeographicTextPresentationSeq(c rune) bool {
	return inRanges(textPresentationSeq[:], c)
}

// isEmojiModifierBase: whether c is an Emoji_Modifier_Base.
func isEmojiModifierBase(c rune) bool {
	return inRanges(emojiModifierBase[:], c)
}
