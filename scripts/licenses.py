#!/usr/bin/env python3
"""Writes the Go-library section of THIRD_PARTY_NOTICES.md: the licence of every
Go module linked into the coigue binary.

A binary that carries other people's code carries their notices (MIT and BSD
both ask for it), so every distribution of the executable carries
THIRD_PARTY_NOTICES.md. The set is what `go list -deps` finds for the command on the
platforms Coigüe is built for, so a module only one build links is not missed.
The theme notices above the generated section are written by hand.

Run it whenever go.mod changes (for example after the Brote branch is merged);
TestEveryRequiredModuleHasANotice fails until it has been, and CI runs --check.

    python3 scripts/licenses.py          # rewrite the section
    python3 scripts/licenses.py --check  # fail if the section is out of date

The modules must be in the module cache: run `go mod download` first.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD_PARTY_NOTICES.md")
BEGIN = "<!-- BEGIN GO LIBRARIES: generated by scripts/licenses.py, do not edit by hand -->"
END = "<!-- END GO LIBRARIES -->"
NAMES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "COPYING", "COPYING.txt", "NOTICE", "NOTICE.md", "NOTICE.txt")
PLATFORMS = (("linux", "amd64"), ("darwin", "amd64"), ("darwin", "arm64"))


def linked():
    """The (path, version, dir) of every module linked on some platform."""
    found = {}
    fmt = "{{if .Module}}{{if not .Module.Main}}{{.Module.Path}} {{.Module.Version}} {{.Module.Dir}}{{end}}{{end}}"
    for goos, goarch in PLATFORMS:
        env = dict(os.environ, GOOS=goos, GOARCH=goarch, CGO_ENABLED="0", GOFLAGS="-mod=readonly")
        run = subprocess.run(["go", "list", "-deps", "-f", fmt, "./cmd/coigue"], cwd=ROOT, env=env, capture_output=True, text=True)
        if run.returncode != 0:
            sys.exit(f"go list ({goos}/{goarch}) failed:\n{run.stderr}")
        for line in run.stdout.splitlines():
            parts = line.split(" ", 2)
            if len(parts) == 3:
                found[parts[0]] = (parts[1], parts[2])
    return sorted((path, v, d) for path, (v, d) in found.items())


def render():
    out = [
        BEGIN,
        "",
        "## Go libraries",
        "",
        "The Go libraries linked into the `coigue` executable, with the licence each is under.",
        "Generated by `scripts/licenses.py` from the modules `go list -deps` finds.",
    ]
    for path, version, directory in linked():
        if not directory or not os.path.isdir(directory):
            sys.exit(f"{path} {version} is not in the module cache: run `go mod download` and try again")
        texts = []
        for name in NAMES:
            file = os.path.join(directory, name)
            if os.path.isfile(file):
                with open(file, encoding="utf-8", errors="replace") as f:
                    texts.append(f.read().strip("\n"))
        if not texts:
            sys.exit(f"{path} {version} has no licence file")
        out.append(f"\n### Go library: {path} {version}\n\n" + "\n\n".join(texts))
    out += ["", END]
    return "\n".join(out) + "\n"


def splice(current, section):
    """current with the generated section replaced, or appended if it has none."""
    start = current.find(BEGIN)
    end = current.find(END)
    if start < 0 or end < start:
        return current.rstrip("\n") + "\n\n" + section
    return current[:start] + section + current[end + len(END):].lstrip("\n")


def main():
    with open(OUT, encoding="utf-8") as f:
        current = f.read()
    updated = splice(current, render())
    if "--check" in sys.argv[1:]:
        if current != updated:
            sys.exit(f"{OUT} is out of date: run python3 scripts/licenses.py")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(updated)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
